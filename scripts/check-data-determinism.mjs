#!/usr/bin/env node
/**
 * Data-determinism gate.
 *
 * Regenerates the synthetic dataset into a temporary directory (via scripts/generate-synthetic-data.mjs --out)
 * and compares every file byte-for-byte with the committed copy in data/. The committed files, the figures in the
 * README and the screenshots all depend on generateDataset() producing exactly the same bytes, so any difference —
 * including a changed CSV serialisation — fails the check.
 *
 *   npm run check:data                                           compare a fresh generation with data/
 *   node scripts/check-data-determinism.mjs --expected <dir>     compare with another directory
 *   node scripts/check-data-determinism.mjs --keep               keep the temporary directory for inspection
 *
 * Exit code 0: all files identical. Exit code 1: generator failure, differing, missing or unexpected files.
 */
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const generator = join(repoRoot, "scripts", "generate-synthetic-data.mjs");
const args = process.argv.slice(2);
const keep = args.includes("--keep");
const expectedDir = resolve(repoRoot, optionValue("--expected") ?? "data");

function optionValue(flag) {
  const i = args.indexOf(flag);
  return i === -1 ? undefined : args[i + 1];
}

/** Path of the tsx CLI (the generator imports TypeScript sources), resolved from the installed package. */
function tsxCli() {
  const require = createRequire(import.meta.url);
  const pkgPath = require.resolve("tsx/package.json");
  const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
  const bin = typeof pkg.bin === "string" ? pkg.bin : pkg.bin.tsx;
  return join(dirname(pkgPath), bin);
}

function listFiles(dir) {
  return readdirSync(dir)
    .filter((name) => statSync(join(dir, name)).isFile())
    .sort();
}

function sha256(buf) {
  return createHash("sha256").update(buf).digest("hex");
}

/** Index of the first differing byte, or -1 when both buffers are identical. */
function firstDifference(a, b) {
  const n = Math.min(a.length, b.length);
  for (let i = 0; i < n; i++) if (a[i] !== b[i]) return i;
  return a.length === b.length ? -1 : n;
}

function lineOf(buf, offset) {
  let line = 1;
  for (let i = 0; i < offset && i < buf.length; i++) if (buf[i] === 10) line += 1;
  return line;
}

function compare(expectedPath, generatedPath) {
  if (!existsSync(generatedPath)) return { status: "MISSING in generated output", ok: false };
  if (!existsSync(expectedPath)) return { status: "UNEXPECTED (not in expected directory)", ok: false };
  const expected = readFileSync(expectedPath);
  const generated = readFileSync(generatedPath);
  const diff = firstDifference(expected, generated);
  const row = {
    expectedBytes: expected.length,
    generatedBytes: generated.length,
    expectedSha: sha256(expected).slice(0, 12),
    generatedSha: sha256(generated).slice(0, 12),
  };
  if (diff === -1) return { ...row, status: "identical", ok: true };
  return { ...row, status: `DIFFERS at byte ${diff} (line ${lineOf(expected, diff)})`, ok: false };
}

function printTable(rows) {
  const headers = ["file", "expected bytes", "generated bytes", "sha256 expected", "sha256 generated", "result"];
  const cells = rows.map((r) => [
    r.name,
    r.expectedBytes === undefined ? "-" : String(r.expectedBytes),
    r.generatedBytes === undefined ? "-" : String(r.generatedBytes),
    r.expectedSha ?? "-",
    r.generatedSha ?? "-",
    r.status,
  ]);
  const widths = headers.map((h, i) => Math.max(h.length, ...cells.map((c) => c[i].length)));
  const line = (c) => c.map((v, i) => (i === 1 || i === 2 ? v.padStart(widths[i]) : v.padEnd(widths[i]))).join("  ");
  console.log(line(headers));
  console.log(widths.map((w) => "-".repeat(w)).join("  "));
  for (const c of cells) console.log(line(c));
}

function main() {
  if (!existsSync(expectedDir) || !statSync(expectedDir).isDirectory()) {
    console.error(`check:data: expected directory not found: ${expectedDir}`);
    return 1;
  }
  const tmp = mkdtempSync(join(tmpdir(), "tkm-synthetic-"));
  try {
    const gen = spawnSync(process.execPath, [tsxCli(), generator, "--out", tmp], { cwd: repoRoot, encoding: "utf8", timeout: 180_000 });
    if (gen.error || gen.status !== 0) {
      if (gen.stdout) console.error(gen.stdout.trim());
      if (gen.stderr) console.error(gen.stderr.trim());
      console.error(`check:data: generator failed (${gen.error ? gen.error.message : `exit code ${gen.status}`})`);
      return 1;
    }
    const names = [...new Set([...listFiles(expectedDir), ...listFiles(tmp)])].sort();
    const rows = names.map((name) => ({ name, ...compare(join(expectedDir, name), join(tmp, name)) }));
    console.log(`check:data: comparing a fresh generation with ${relative(repoRoot, expectedDir) || "."}/`);
    printTable(rows);
    const identical = rows.filter((r) => r.ok).length;
    if (identical === rows.length && rows.length > 0) {
      console.log(`check:data OK — ${identical}/${rows.length} files byte-identical`);
      return 0;
    }
    console.error(`check:data FAILED — ${rows.length - identical} of ${rows.length} files differ, are missing or unexpected`);
    return 1;
  } finally {
    if (keep) console.log(`check:data: generated files kept in ${tmp}`);
    else rmSync(tmp, { recursive: true, force: true });
  }
}

process.exit(main());
